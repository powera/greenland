#!/usr/bin/python3

"""Routes for the story library ("texts"): browsing, creating, and editing
text works and their versions.

A text work is the story/conversation/song/poem itself, as opposed to the
encyclopedia entry about it (see docs/fables_design.md). Authored works
(fables, folk tales, conversations, ...) get their texts generated by the
Ožys agent; canonical works (poems, songs, ...) get their single authoritative
text pasted in with a source and a required license.
"""

