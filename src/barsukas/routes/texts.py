from typing import TYPE_CHECKING, Optional, cast

import constants
from flask import (
    Blueprint,
    current_app,
    flash,
    g,
    redirect,
    render_template,
    request,
    url_for,
)
from flask.typing import ResponseReturnValue

from barsukas.helpers.wikilinks import render_text_body
from storage.backend.config import DataSourceConfig
from storage.crud.concept import get_wikidata_index
from storage.crud.text_work import (
    create_text_version,
    create_text_work,
    delete_text_version,
    delete_text_work,
    get_text_version_by_id,
    get_text_version_for_slot,
    get_text_work_by_slug,
    update_text_version,
    update_text_work,
)
from storage.models.concept import normalize_concept_slug
from storage.models.text_work import (
    ALL_TEXT_TYPES,
    TEXT_TYPE_GROUPS,
    TextVersion,
    TextWork,
    is_intake_deferred_text_type,
)
from storage.queries.text_work import count_text_works, list_text_works
