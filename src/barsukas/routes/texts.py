from storage.wikidata import normalize_qid

if TYPE_CHECKING:
    from barsukas.app import BarsukasFlask
    from sqlalchemy.orm import Session

logger = logging.getLogger(__name__)

bp = Blueprint("texts", __name__, url_prefix="/texts")

TEXTS_PER_PAGE = 50

# License choices for canonical texts (free-form "Other" goes in text notes).
CANONICAL_LICENSE_CHOICES: tuple[str, ...] = (
    "public-domain",
    "CC0",
    "CC-BY",
    "CC-BY-SA",
    "developer-authored",
)


def _get_config() -> DataSourceConfig:
    """Return the Flask app's DataSourceConfig."""
    app: "BarsukasFlask" = current_app  # type: ignore[assignment]
    return app.backend_config


def _is_readonly() -> bool:
    """Return True if text editing should be disabled."""
    if bool(current_app.config.get("CONCEPTS_WRITABLE", False)):
        return False
    return bool(current_app.config.get("READONLY", False))


def _texts_session() -> "Session":
    """Return the session that owns text-work reads and writes.

    Text works live in the concepts database/backend (same posture as
    concepts: outside the lemma machinery).
    """
    return cast("Session", getattr(g, "concepts_db", g.db))


def _outbound_allowed() -> bool:
    """Return True if outbound LLM calls are permitted."""
    return bool(current_app.config.get("ALLOW_OUTBOUND_CALLS", True))


def _selectable_text_types() -> list[str]:
    """Text types accepted at intake (deferred types like 'quote' excluded)."""
    return [t for t in ALL_TEXT_TYPES if not is_intake_deferred_text_type(t)]


def _resolve_encyclopedia_target(qid: Optional[str]) -> Optional[dict]:
    """Resolve a Q-id through the shared index to its encyclopedia page.

    Returns a small dict for the template ({"kind", "slug", "title", "qid"}),
    or None when the Q-id is absent or has no concept/sub-concept yet.
    """
    if not qid:
        return None
    row = get_wikidata_index(_texts_session(), qid)
    if row is None:
        return None
    if row.concept is not None:
        return {"kind": "concept", "slug": row.concept.slug, "title": row.concept.title, "qid": qid}
    if row.sub_concept is not None:
        return {
            "kind": "sub_concept",
            "slug": row.sub_concept.slug,
            "title": row.sub_concept.title,
            "qid": qid,
        }
    return None


def _parse_difficulty(raw: str) -> Optional[int]:
    """Parse an optional difficulty form field ("" -> None)."""
    raw = raw.strip()
    if not raw:
        return None
    return int(raw)


@bp.route("/")
def list_texts_view() -> ResponseReturnValue:
    """List text works with optional search, type filter, and pagination."""
    search = request.args.get("q", "").strip()
    text_type = request.args.get("type", "").strip()
    if text_type not in ALL_TEXT_TYPES:
        text_type = ""

    total = count_text_works(_texts_session(), search=search, text_type=text_type or None)
    total_pages = max(1, (total + TEXTS_PER_PAGE - 1) // TEXTS_PER_PAGE)

    try:
        page = int(request.args.get("page", "1"))
    except ValueError:
        page = 1
    page = max(1, min(page, total_pages))

    works = list_text_works(
        _texts_session(),
        search=search,
        text_type=text_type or None,
        limit=TEXTS_PER_PAGE,
        offset=(page - 1) * TEXTS_PER_PAGE,
    )
    return render_template(
        "texts/list.html",
        works=works,
        total=total,
        search=search,
        text_type=text_type,
        type_groups=TEXT_TYPE_GROUPS,
        readonly=_is_readonly(),
        page=page,
        total_pages=total_pages,
    )


@bp.route("/new")
def new_work() -> ResponseReturnValue:
    """Render the add-a-work form."""
    if _is_readonly():
        flash("Cannot create texts in read-only mode", "error")
        return redirect(url_for("texts.list_texts_view"))
    return render_template(
        "texts/form.html",
        work=None,
        type_groups=TEXT_TYPE_GROUPS,
        selectable_types=_selectable_text_types(),
    )


@bp.route("/create", methods=["POST"])
def create() -> ResponseReturnValue:
    """Create a text work from a Wikidata Q-id, or manually by title."""
    if _is_readonly():
        flash("Cannot create texts in read-only mode", "error")
        return redirect(url_for("texts.list_texts_view"))

    text_type = request.form.get("text_type", "")
    if text_type not in _selectable_text_types():
        flash("A text type is required.", "error")
        return redirect(url_for("texts.new_work"))

    wikidata_qid = normalize_qid(request.form.get("wikidata_qid", ""))
    title = request.form.get("title", "").strip()
    attribution = request.form.get("attribution", "").strip() or None
    attribution_qid_raw = request.form.get("attribution_qid", "").strip()
    attribution_qid: Optional[str] = None
    if attribution_qid_raw:
        attribution_qid = normalize_qid(attribution_qid_raw)
        if attribution_qid is None:
            flash(f"Invalid attribution Q-id {attribution_qid_raw!r}.", "error")
            return redirect(url_for("texts.new_work"))
    summary = request.form.get("summary", "").strip()
    notes = request.form.get("notes", "").strip() or None

    # Q-id-seeded creation goes through the shared service (seed fetch,
    # idempotency), mirroring the concepts create flow.
    if wikidata_qid is not None:
        result = create_text_work_from_qid(
            _texts_session(),
            wikidata_qid,
            text_type,
            attribution_qid=attribution_qid,
            attribution=attribution,
            notes=notes,
        )
        if result.status == "exists":
            flash(f"Wikidata ID {wikidata_qid}: {result.detail}.", "error")
            if result.work is not None:
                return redirect(url_for("texts.detail", slug=result.work.slug))
            return redirect(url_for("texts.new_work"))
        if result.work is None:
            flash(f"Could not create the work: {result.detail or result.status}.", "error")
            return redirect(url_for("texts.new_work"))
        flash(f"Added {result.work.title!r} to the library.", "success")
        return redirect(url_for("texts.detail", slug=result.work.slug))

    # Manual creation (the only route for conversations, which have no Q-id).
    if not title:
        flash("A title or Wikidata Q-id is required.", "error")
        return redirect(url_for("texts.new_work"))
    if get_text_work_by_slug(_texts_session(), title) is not None:
        flash(f"A work titled {title!r} already exists.", "error")
        return redirect(url_for("texts.new_work"))

    work = create_text_work(
        _texts_session(),
        title=title,
        text_type=text_type,
        attribution_qid=attribution_qid,
        attribution=attribution,
        summary=summary or None,
        notes=notes,
    )
    if work is None:
        flash("Failed to create the work.", "error")
        return redirect(url_for("texts.new_work"))

    flash(f"Added {work.title!r} to the library.", "success")
    return redirect(url_for("texts.detail", slug=work.slug))


@bp.route("/<path:slug>")
def detail(slug: str) -> ResponseReturnValue:
    """Show a work with its rendered versions and encyclopedia cross-links."""
    work = get_text_work_by_slug(_texts_session(), slug)
    if work is None:
        flash(f"No text work found for {slug!r}.", "error")
        return redirect(url_for("texts.list_texts_view"))

    rendered_versions = [
        (version, render_text_body(version.body or "")) for version in work.versions
    ]
    return render_template(
        "texts/detail.html",
        work=work,
        rendered_versions=rendered_versions,
        work_page=_resolve_encyclopedia_target(work.qid),
        attribution_page=_resolve_encyclopedia_target(work.attribution_qid),
        license_choices=CANONICAL_LICENSE_CHOICES,
        default_model=constants.DEFAULT_MODEL,
        readonly=_is_readonly(),
        outbound_allowed=_outbound_allowed(),
    )


