@bp.route("/<path:slug>/generate", methods=["POST"])
def generate(slug: str) -> ResponseReturnValue:
    """Generate (or regenerate) a telling for an authored work via Ožys."""
    if _is_readonly():
        flash("Cannot generate in read-only mode", "error")
        return redirect(url_for("texts.detail", slug=slug))
    if not _outbound_allowed():
        flash("Outbound calls are disabled; cannot generate.", "error")
        return redirect(url_for("texts.detail", slug=slug))

    work = get_text_work_by_slug(_texts_session(), slug)
    if work is None:
        flash(f"No text work found for {slug!r}.", "error")
        return redirect(url_for("texts.list_texts_view"))
    if not work.is_authored:
        flash("Canonical works are transcribed, not generated.", "error")
        return redirect(url_for("texts.detail", slug=slug))

    model = request.form.get("model", "").strip() or constants.DEFAULT_MODEL
    try:
        difficulty_level = _parse_difficulty(request.form.get("difficulty", ""))
    except ValueError:
        flash("Difficulty must be a whole number (or blank).", "error")
        return redirect(url_for("texts.detail", slug=slug))

    existing = get_text_version_for_slot(_texts_session(), work, "en", difficulty_level)
    if existing is not None and existing.verified:
        flash("That version is verified; un-verify it before regenerating.", "error")
        return redirect(url_for("texts.detail", slug=slug))

    # Imported lazily so the route module stays importable without LLM clients.
    from agents.ozys import OzysAgent

    try:
        agent = OzysAgent(_get_config(), model=model)
        body = agent.generate_for_work(work, difficulty_level=difficulty_level)
    except Exception as exc:
        logger.exception("Text generation failed for %r", work.slug)
        flash(f"Generation failed: {exc}", "error")
        return redirect(url_for("texts.detail", slug=slug))

    if existing is not None:
        version = update_text_version(
            _texts_session(), existing, body=body, source_model=model, verified=False
        )
    else:
        version = create_text_version(
            _texts_session(),
            work,
            lang="en",
            body=body,
            difficulty_level=difficulty_level,
            source_model=model,
        )
    if version is None:
        flash("Generated a text but failed to store it.", "error")
        return redirect(url_for("texts.detail", slug=slug))

    flash(f"Generated the {version.variant_label} version.", "success")
    return redirect(url_for("texts.detail", slug=slug))


@bp.route("/<path:slug>/versions/add", methods=["POST"])
def add_canonical_version(slug: str) -> ResponseReturnValue:
    """Add the canonical text of a canonical-type work (paste + license)."""
    if _is_readonly():
        flash("Cannot add texts in read-only mode", "error")
        return redirect(url_for("texts.detail", slug=slug))

    work = get_text_work_by_slug(_texts_session(), slug)
    if work is None:
        flash(f"No text work found for {slug!r}.", "error")
        return redirect(url_for("texts.list_texts_view"))
    if work.is_authored:
        flash("Authored works get their texts generated, not pasted.", "error")
        return redirect(url_for("texts.detail", slug=slug))

    body = request.form.get("body", "").strip()
    text_source = request.form.get("text_source", "").strip()
    license = request.form.get("license", "").strip()
    if license not in CANONICAL_LICENSE_CHOICES:
        flash("A license is required for a canonical text.", "error")
        return redirect(url_for("texts.detail", slug=slug))

    version = create_text_version(
        _texts_session(),
        work,
        lang="en",
        body=body or None,
        is_canonical=True,
        text_source=text_source or None,
        license=license,
    )
    if version is None:
        flash("Could not add the canonical text (one may already exist).", "error")
        return redirect(url_for("texts.detail", slug=slug))

    flash("Added the canonical text.", "success")
    return redirect(url_for("texts.detail", slug=slug))


def _get_version_for_work(
    slug: str, version_id: int
) -> tuple[Optional[TextWork], Optional[TextVersion]]:
    """Return (work, version) when the version belongs to the slug's work."""
    work = get_text_work_by_slug(_texts_session(), slug)
    if work is None:
        return None, None
    version = get_text_version_by_id(_texts_session(), version_id)
    if version is None or version.work_id != work.id:
        return work, None
    return work, version


@bp.route("/<path:slug>/versions/<int:version_id>/edit")
def edit_version(slug: str, version_id: int) -> ResponseReturnValue:
    """Render the edit form for one version of a work."""
    if _is_readonly():
        flash("Cannot edit texts in read-only mode", "error")
        return redirect(url_for("texts.detail", slug=slug))

    work, version = _get_version_for_work(slug, version_id)
    if work is None or version is None:
        flash("No such version.", "error")
        return redirect(
            url_for("texts.detail", slug=slug) if work else url_for("texts.list_texts_view")
        )

    return render_template(
        "texts/version_form.html",
        work=work,
        version=version,
        license_choices=CANONICAL_LICENSE_CHOICES,
    )


@bp.route("/<path:slug>/versions/<int:version_id>/update", methods=["POST"])
def update_version(slug: str, version_id: int) -> ResponseReturnValue:
    """Apply edits to a version (body, difficulty, source/license, verified)."""
    if _is_readonly():
        flash("Cannot edit texts in read-only mode", "error")
        return redirect(url_for("texts.detail", slug=slug))

    work, version = _get_version_for_work(slug, version_id)
    if work is None or version is None:
        flash("No such version.", "error")
        return redirect(
            url_for("texts.detail", slug=slug) if work else url_for("texts.list_texts_view")
        )

    try:
        difficulty_level = _parse_difficulty(request.form.get("difficulty", ""))
    except ValueError:
        flash("Difficulty must be a whole number (or blank).", "error")
        return redirect(url_for("texts.edit_version", slug=slug, version_id=version_id))

    updated = update_text_version(
        _texts_session(),
        version,
        body=request.form.get("body", ""),
        difficulty_level=difficulty_level,
        text_source=request.form.get("text_source", "").strip(),
        license=request.form.get("license", "").strip() or None,
        verified=request.form.get("verified") == "1",
        notes=request.form.get("notes", "").strip(),
    )
    if updated is None:
        flash(
            "Failed to update the version (occupied difficulty slot, or a "
            "canonical version cannot lose its license).",
            "error",
        )
        return redirect(url_for("texts.edit_version", slug=slug, version_id=version_id))

    flash("Version updated.", "success")
    return redirect(url_for("texts.detail", slug=work.slug))


@bp.route("/<path:slug>/versions/<int:version_id>/delete", methods=["POST"])
def delete_version(slug: str, version_id: int) -> ResponseReturnValue:
    """Delete one version of a work."""
    if _is_readonly():
        flash("Cannot delete in read-only mode", "error")
        return redirect(url_for("texts.detail", slug=slug))

    work, version = _get_version_for_work(slug, version_id)
    if work is None or version is None:
        flash("No such version.", "error")
        return redirect(
            url_for("texts.detail", slug=slug) if work else url_for("texts.list_texts_view")
        )

    delete_text_version(_texts_session(), version)
    flash("Deleted the version.", "success")
    return redirect(url_for("texts.detail", slug=work.slug))
