def flatten(articles: Dict[str, List[str]]) -> List[str]:
    """Every title in a grouped article list, de-duplicated, in list order."""
    seen: Dict[str, None] = {}
    for titles in articles.values():
        for title in titles:
            seen.setdefault(title, None)
    return list(seen)


