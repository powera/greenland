def flatten(articles: Dict[str, List[str]]) -> List[str]:
    """Every title in a grouped article list, de-duplicated, in list order."""
    seen: Dict[str, None] = {}
    for titles in articles.values():
        for title in titles:
            seen.setdefault(title, None)
    return list(seen)


def all_article_titles() -> List[str]:
    """Every vital-article title, flattened and de-duplicated, in list order."""
    return flatten(VITAL_ARTICLES)


def all_math_titles() -> List[str]:
    """Every mathematics title, flattened and de-duplicated, in list order."""
    return flatten(MATH_ARTICLES)
